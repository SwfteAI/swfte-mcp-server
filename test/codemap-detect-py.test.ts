const NO_LOCKS: DetectContext = { locks: [], lockDir: null };

interface Run {
  sites: DetectedSite[];
  implementations: Implementation[];
  envVarNames: string[];
}

/** Run every Python detector over one in-memory file and gather what they report. */
function run(text: string, relPath = 'app/svc.py', ctx: DetectContext = NO_LOCKS): Run {
  const out: Run = { sites: [], implementations: [], envVarNames: [] };
  for (const d of PY) {
    const r = d.detect({ relPath, language: 'python', text }, ctx);
    out.sites.push(...r.sites);
    out.implementations.push(...r.implementations);
    out.envVarNames.push(...r.envVarNames);
  }
  out.sites.sort((a, b) => a.line - b.line);
  return out;
}


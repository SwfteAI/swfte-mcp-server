describe('py corpus', () => {
  type KeySite = { path: string; line: number; language: string; category: string; symbol: string; sdk: string; op: string; managed: string; artifact: { kind: string; id: string | null; unresolved: boolean; envVarName?: string | null; alias?: string | null; pinnedVersion?: string | null }; inputKeys: string[]; outputKeys: string[] };

  async function compare(fixture: string, under = '') {
    const root = join(CORPUS, fixture);
    const key = JSON.parse(fs.readFileSync(join(root, 'answer-key.json'), 'utf8')) as { sites: KeySite[]; implementations: { path: string; line: number }[] };
    const out = await detectProject(root, { detectors: PY, envFiles: ENV_FILES });
    const want = key.sites.filter((s) => s.path.endsWith('.py') && s.path.startsWith(under));
    const got = out.sites.filter((s) => s.relPath.endsWith('.py'));
    assert.ok(want.length > 0, 'the fixture has Python sites');
    const fmt = (s: { path: string; line: number; artifact: KeySite['artifact']; inputKeys: string[]; outputKeys: string[] }) =>
      JSON.stringify([s.path, s.line, s.artifact.kind, s.artifact.id, s.artifact.unresolved, s.artifact.envVarName ?? null, s.artifact.alias ?? null, s.artifact.pinnedVersion ?? null, s.inputKeys, s.outputKeys]);
    assert.deepEqual(
      got.map((s) => fmt({ ...s, path: s.relPath })),
      want.map((s) => fmt(s)),
    );
    // category, symbol and transport agree too
    const by = new Map(got.map((s) => [`${s.relPath}:${s.line}`, s]));
    for (const w of want) {
      const g = by.get(`${w.path}:${w.line}`)!;
      assert.deepEqual([g.category, g.symbol, g.sdk, g.op, g.managed], [w.category, w.symbol, w.sdk, w.op, w.managed], `${w.path}:${w.line}`);
    }
    const implWant = key.implementations.filter((i) => i.path.endsWith('.py')).map((i) => `${i.path}:${i.line}`);
    assert.deepEqual(out.implementations.filter((i) => i.relPath.endsWith('.py')).map((i) => `${i.relPath}:${i.line}`), implWant);
  }

  test('py-fastapi: every answer-key site is found with the same path, line, artifact and keys', async () => {
    await compare('py-fastapi');
  });

  test('monorepo: the Python worker package resolves to its own lock', async () => {
    await compare('monorepo', 'py/');
  });
});


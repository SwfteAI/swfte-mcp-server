/**
 * Reuse-first tools: ask Studio what already exists, and how well it is proven,
 * before generating anything.
 *
 * Generating a workflow costs tens of thousands of tokens and minutes of wall
 * time, and produces something with no run history. A catalog entry that has
 * already run a hundred times is cheaper and better evidenced. These tools make
 * that trade the first thing a coding agent sees.
 */

// Tree helpers

/** A node in (or containing) a syntax error: edge case E8 says a broken region yields no sites. */
export function isBroken(n: JNode): boolean {
  if (n.hasError || n.isMissing) return true;
  for (let p = n.parent; p; p = p.parent) if (p.type === 'ERROR') return true;
  return false;
}

export const lineOf = (n: JNode): number => n.startPosition.row + 1;

export function children(n: JNode): JNode[] {
  const out: JNode[] = [];
  for (let i = 0; i < n.namedChildCount; i++) {
    const c = n.namedChild(i);
    if (c && c.type !== 'line_comment' && c.type !== 'block_comment') out.push(c);
  }
  return out;
}

/** Depth-first walk over named nodes; `visit` returning false prunes the subtree. */
export function walk(n: JNode, visit: (n: JNode) => boolean | void): void {
  if (visit(n) === false) return;
  for (let i = 0; i < n.namedChildCount; i++) {
    const c = n.namedChild(i);
    if (c) walk(c, visit);
  }
}

export const argsOf = (call: JNode): JNode[] => {
  const a = call.childForFieldName('arguments');
  return a ? children(a) : [];
};

/** The name of a method call (`invoke` in `client.workflows().invoke(...)`). */
export const nameOf = (call: JNode): string => call.childForFieldName('name')?.text ?? '';

const TYPE_DECLS = new Set(['class_declaration', 'interface_declaration', 'enum_declaration', 'record_declaration', 'annotation_type_declaration']);
const isTypeDecl = (n: JNode): boolean => TYPE_DECLS.has(n.type);

const isAnonymousBody = (classBody: JNode): boolean => classBody.parent?.type === 'object_creation_expression' || classBody.parent?.type === 'enum_constant';

function methodsNamed(typeDecl: JNode, name: string, ctor: boolean): number {
  const body = typeDecl.childForFieldName('body');
  if (!body) return 0;
  let n = 0;
  for (const c of children(body)) {
    if (c.type === (ctor ? 'constructor_declaration' : 'method_declaration') && c.childForFieldName('name')?.text === name) n++;
  }
  return n;
}

function arityOf(m: JNode): number {
  const params = m.childForFieldName('parameters');
  return params ? children(params).length : 0;
}

/**
 * `Class.method` (overloads `Class.method#<arity>`), `Class.<init>` (constructors, instance field
 * initialisers and instance blocks), `Class.<clinit>` (static fields and blocks). Lambdas and anonymous
 * class bodies contribute nothing (D2): the nearest NAMED enclosing symbol wins. A nested type is named by
 * its own simple name.
 */
export function symbolOf(n: JNode): string {
  for (let p: JNode | null = n.parent; p; p = p.parent) {
    const owner = (): JNode | null => {
      for (let t: JNode | null = p!.parent; t; t = t.parent) {
        if (t.type === 'class_body' && isAnonymousBody(t)) return null;
        if (isTypeDecl(t)) return t;
      }
      return null;
    };
    const cls = (t: JNode | null): string | null => t?.childForFieldName('name')?.text ?? null;
    switch (p.type) {
      case 'method_declaration': {
        if (p.parent?.type === 'class_body' && isAnonymousBody(p.parent)) continue;
        const t = owner();
        const c = cls(t);
        const name = p.childForFieldName('name')?.text;
        if (!name) continue;
        const overloaded = t ? methodsNamed(t, name, false) > 1 : false;
        const sym = `${c ? `${c}.` : ''}${name}${overloaded ? `#${arityOf(p)}` : ''}`;
        return sym;
      }
      case 'constructor_declaration': {
        const t = owner();
        const c = cls(t);
        if (!c) continue;
        const overloaded = methodsNamed(t!, c, true) > 1;
        return `${c}.<init>${overloaded ? `#${arityOf(p)}` : ''}`;
      }
      case 'compact_constructor_declaration': {
        const c = cls(owner());
        if (c) return `${c}.<init>`;
        continue;
      }
      case 'enum_constant': {
        const c = cls(owner());
        if (c) return `${c}.<clinit>`;
        continue;
      }
      case 'static_initializer': {
        const c = cls(owner());
        if (c) return `${c}.<clinit>`;
        continue;
      }
      case 'field_declaration': {
        if (p.parent?.type !== 'class_body' || isAnonymousBody(p.parent)) continue;
        const t = owner();
        const c = cls(t);
        if (!c) continue;
        const isStatic = t?.type === 'interface_declaration' || /\bstatic\b/.test(p.children.find((x) => x?.type === 'modifiers')?.text ?? '');
        return `${c}.${isStatic ? '<clinit>' : '<init>'}`;
      }
      case 'block': {
        if (p.parent?.type !== 'class_body' || isAnonymousBody(p.parent)) continue;
        const c = cls(owner());
        if (c) return `${c}.<init>`;
        continue;
      }
      default:
        continue;
    }
  }
  return '<module>';
}


// Scopes and what a name holds

const isMethodScope = (n: JNode): boolean =>
  n.type === 'method_declaration' || n.type === 'constructor_declaration' || n.type === 'compact_constructor_declaration' || n.type === 'static_initializer' || n.type === 'lambda_expression';

/** The nearest enclosing method-like node (lambda included), or null at class level. */
export function enclosingMethod(n: JNode | null): JNode | null {
  for (let p = n; p; p = p.parent) if (isMethodScope(p)) return p;
  return null;
}

/** The nearest enclosing method or constructor that is not a lambda. */
export function enclosingNamedMethod(n: JNode | null): JNode | null {
  for (let p = n; p; p = p.parent) if (isMethodScope(p) && p.type !== 'lambda_expression') return p;
  return null;
}

export function enclosingType(n: JNode | null): JNode | null {
  for (let p = n; p; p = p.parent) if (isTypeDecl(p)) return p;
  return null;
}

/** The statement-level ancestors (blocks) between a node and its method, innermost first. */
export function enclosingBlock(n: JNode): JNode | null {
  for (let p: JNode | null = n.parent; p; p = p.parent) if (p.type === 'block' || p.type === 'constructor_body' || p.type === 'switch_block') return p;
  return null;
}

/** String content of a string literal when it is one plain literal (no concatenation), else null. */
export function plainString(n: JNode | null | undefined): string | null {
  if (!n || n.type !== 'string_literal') return null;
  return literalOf(stringPieces(n));
}

const ESCAPES: Record<string, string> = { n: '\n', t: '\t', r: '\r', b: '\b', f: '\f', s: ' ', '"': '"', "'": "'", '\\': '\\', '0': '\0' };

export function unescapeJava(s: string): string {
  if (s.startsWith('\\u')) {
    const code = Number.parseInt(s.slice(2), 16);
    return Number.isFinite(code) ? String.fromCharCode(code) : s;
  }
  return ESCAPES[s.slice(1)] ?? s;
}

/** Literal text of a `string_literal` (regular or text block). */
export function stringPieces(n: JNode): Piece[] {
  const out: Piece[] = [];
  for (let i = 0; i < n.namedChildCount; i++) {
    const c = n.namedChild(i);
    if (!c) continue;
    if (c.type === 'string_fragment' || c.type === 'multiline_string_fragment') out.push({ k: 'lit', v: c.text });
    else if (c.type === 'escape_sequence') out.push({ k: 'lit', v: unescapeJava(c.text) });
  }
  return mergePieces(out);
}

const ENV_NAME = /^[A-Za-z_][A-Za-z0-9_]{0,127}$/;
const ENV_STYLE = /^[A-Z][A-Z0-9_]{0,127}$/;

/** `System.getenv("X")` and `System.getenv().get("X")`: the env var NAME. */
export function envNameOf(n: JNode): string | null {
  if (n.type !== 'method_invocation') return null;
  const name = nameOf(n);
  const obj = n.childForFieldName('object');
  const args = argsOf(n);
  const lit = (a: JNode | undefined): string | null => {
    const s = a ? plainString(a) : null;
    return s !== null && ENV_NAME.test(s) ? s : null;
  };
  if (name === 'getenv' && obj?.text === 'System' && args.length === 1) return lit(args[0]);
  if (name === 'get' && obj?.type === 'method_invocation' && nameOf(obj) === 'getenv' && obj.childForFieldName('object')?.text === 'System' && argsOf(obj).length === 0) return lit(args[0]);
  return null;
}

/** The env var name inside a Spring `@Value("${NAME}")` / `${NAME:default}` placeholder, only when it is env-shaped. */
export function valueAnnotationEnv(annotations: JNode[]): string | null {
  for (const a of annotations) {
    if (a.type !== 'annotation' || a.childForFieldName('name')?.text !== 'Value') continue;
    const arg = a.childForFieldName('arguments');
    const lit = arg ? children(arg).find((c) => c.type === 'string_literal') : undefined;
    const s = lit ? plainString(lit) : null;
    const m = s ? /^\$\{([A-Za-z0-9_.-]+)(?::[^}]*)?\}$/.exec(s) : null;
    if (m && ENV_STYLE.test(m[1]!)) return m[1]!;
  }
  return null;
}

const annotationsOf = (n: JNode): JNode[] => {
  const mods = n.children.find((c) => c && c.type === 'modifiers');
  return mods ? children(mods).filter((c) => c.type === 'annotation' || c.type === 'marker_annotation') : [];
};

const MAX_DEPTH = 8;

function formatPieces(fmt: Piece[], args: JNode[], depth: number): Piece[] {
  const out: Piece[] = [];
  let ai = 0;
  for (const p of fmt) {
    if (p.k !== 'lit') {
      out.push(p);
      continue;
    }
    let last = 0;
    for (const m of p.v.matchAll(/%(?:\d+\$)?[-#+ 0,(]*\d*(?:\.\d+)?[a-zA-Z%]/g)) {
      if (m.index! > last) out.push({ k: 'lit', v: p.v.slice(last, m.index) });
      if (m[0] === '%%') out.push({ k: 'lit', v: '%' });
      else if (m[0] === '%n') out.push({ k: 'lit', v: '\n' });
      else {
        const a = args[ai++];
        out.push(...(a ? evalPieces(a, depth + 1) : [{ k: 'dyn' } as Piece]));
      }
      last = m.index! + m[0].length;
    }
    if (last < p.v.length) out.push({ k: 'lit', v: p.v.slice(last) });
  }
  return mergePieces(out);
}

/** A string expression as pieces: literals, env var names, dynamic holes. Same-file constants are folded. */
export function evalPieces(n: JNode, depth = 0): Piece[] {
  if (depth > MAX_DEPTH) return [{ k: 'dyn' }];
  switch (n.type) {
    case 'string_literal':
      return stringPieces(n);
    case 'parenthesized_expression': {
      const inner = children(n)[0];
      return inner ? evalPieces(inner, depth + 1) : [{ k: 'dyn' }];
    }
    case 'cast_expression': {
      const v = n.childForFieldName('value');
      return v ? evalPieces(v, depth + 1) : [{ k: 'dyn' }];
    }
    case 'binary_expression': {
      const l = n.childForFieldName('left');
      const r = n.childForFieldName('right');
      if (n.childForFieldName('operator')?.text === '+' && l && r) return mergePieces([...evalPieces(l, depth + 1), ...evalPieces(r, depth + 1)]);
      return [{ k: 'dyn' }];
    }
    case 'identifier':
    case 'field_access': {
      if (n.type === 'field_access' && n.childForFieldName('object')?.type !== 'this') return [{ k: 'dyn' }];
      const name = n.type === 'identifier' ? n.text : (n.childForFieldName('field')?.text ?? '');
      const v = lookupName(name, n);
      if (v && typeof v === 'object' && 'env' in v) return [{ k: 'env', name: v.env }];
      return v && v !== 'opaque' && !('env' in v) ? evalPieces(v, depth + 1) : [{ k: 'dyn' }];
    }
    case 'method_invocation': {
      const env = envNameOf(n);
      if (env) return [{ k: 'env', name: env }];
      const name = nameOf(n);
      const obj = n.childForFieldName('object');
      const args = argsOf(n);
      if (name === 'format' && obj?.text === 'String' && args.length >= 1) return formatPieces(evalPieces(args[0]!, depth + 1), args.slice(1), depth);
      if (name === 'formatted' && obj) return formatPieces(evalPieces(obj, depth + 1), args, depth);
      if (name === 'create' && obj?.text === 'URI' && args.length === 1) return evalPieces(args[0]!, depth + 1);
      if (name === 'valueOf' && obj?.text === 'String' && args.length === 1) return evalPieces(args[0]!, depth + 1);
      if (obj && args.length === 0 && /^(?:toString|trim|strip|intern)$/.test(name)) return evalPieces(obj, depth + 1);
      if (obj && name === 'concat' && args.length === 1) return mergePieces([...evalPieces(obj, depth + 1), ...evalPieces(args[0]!, depth + 1)]);
      return [{ k: 'dyn' }];
    }
    case 'object_creation_expression': {
      const t = n.childForFieldName('type')?.text ?? '';
      const args = argsOf(n);
      if ((t === 'URI' || t === 'URL') && args.length === 1) return evalPieces(args[0]!, depth + 1);
      return [{ k: 'dyn' }];
    }
    default:
      return [{ k: 'dyn' }];
  }
}

/** The plain text when every piece is literal, else null. */
export function literalOf(ps: Piece[]): string | null {
  return ps.every((p) => p.k === 'lit') ? ps.map((p) => (p as { v: string }).v).join('') : null;
}


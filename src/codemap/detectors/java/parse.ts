// Paths and files that never hold call sites (decoys): tests, vendored and generated trees.

const VENDORED_DIRS = new Set(['target', 'build', 'out', 'node_modules', '.git', '.gradle', '.idea', 'generated-sources']);

export function isIgnoredPath(relPath: string): boolean {
  const segs = relPath.split('/');
  const base = segs[segs.length - 1] ?? '';
  const dirs = segs.slice(0, -1);
  if (dirs.some((s) => VENDORED_DIRS.has(s))) return true;
  // Maven/Gradle test source roots, then the usual test class names.
  for (let i = 0; i + 1 < dirs.length; i++) if (dirs[i] === 'src' && /^(test|integrationTest|testFixtures|it)$/.test(dirs[i + 1]!)) return true;
  return /(?:Test|Tests|IT|TestCase)\.java$/.test(base) || /^Test[A-Z]\w*\.java$/.test(base);
}

/** Another tool's generated marker in the header, or a `@Generated` annotation on the file's class. */
export function isForeignGenerated(text: string): boolean {
  const head = text.slice(0, 4096).split(/\r?\n/).slice(0, 40).join('\n');
  if (/Generated by @swfte\//.test(head)) return false;
  if (/@generated\b/i.test(head) || /Code generated\b.*\bDO NOT EDIT\b/i.test(head)) return true;
  return /^\s*@(?:[A-Za-z_][\w.]*\.)?Generated\s*\(/m.test(text.slice(0, 8192));
}

/** A file that uses Mockito or Spring's mock beans is a test even when it sits in a main tree. */
export function usesMocks(root: JNode): boolean {
  return children(root).some((n) => n.type === 'import_declaration' && /\borg\.mockito\b|\borg\.springframework\.boot\.test\b|\borg\.junit\b/.test(n.text));
}


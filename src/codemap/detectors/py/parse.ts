// String templates

export type { Piece };

const ESCAPES: Record<string, string> = { n: '\n', t: '\t', r: '\r', '"': '"', "'": "'", '\\': '\\' };

function unescapePy(s: string): string {
  return s.replace(/\\(.)/g, (_m, c: string) => ESCAPES[c] ?? `\\${c}`);
}

function stringPrefix(n: PyNode): string {
  const start = n.child(0);
  return start && start.type === 'string_start' ? start.text.replace(/["']+$/, '').toLowerCase() : '';
}

/** Literal text and holes of a `string` node; f-string holes are evaluated as expressions. */
function stringPieces(n: PyNode, depth: number): Piece[] {
  const prefix = stringPrefix(n);
  const isF = prefix.includes('f');
  const isRaw = prefix.includes('r');
  const out: Piece[] = [];
  for (let i = 0; i < n.childCount; i++) {
    const c = n.child(i);
    if (!c) continue;
    if (c.type === 'string_content') {
      let v = c.text;
      if (isF) v = v.replace(/\{\{/g, '{').replace(/\}\}/g, '}');
      out.push({ k: 'lit', v: isRaw ? v : unescapePy(v) });
    } else if (c.type === 'interpolation') {
      const e = c.childForFieldName('expression');
      out.push(...(e ? evalPieces(e, depth + 1) : [{ k: 'dyn' } as Piece]));
    }
  }
  return out;
}

const ENV_NAME = /^[A-Za-z_][A-Za-z0-9_]{0,127}$/;

/** `os.environ["X"]`, `os.environ.get("X", d)`, `os.getenv("X", d)`, `environ[...]`: the env var NAME. */
export function envNameOf(n: PyNode): string | null {
  const stringArg = (a: PyNode | null): string | null => {
    if (!a || a.type !== 'string') return null;
    const ps = stringPieces(a, 0);
    return ps.length === 1 && ps[0]!.k === 'lit' && ENV_NAME.test(ps[0]!.v) ? ps[0]!.v : null;
  };
  const isEnviron = (o: PyNode | null): boolean => !!o && /^(?:os\.)?environ$/.test(o.text);
  if (n.type === 'subscript') {
    const v = n.childForFieldName('value');
    const sub = n.childForFieldName('subscript');
    return isEnviron(v) ? stringArg(sub) : null;
  }
  if (n.type === 'call') {
    const f = n.childForFieldName('function');
    const args = n.childForFieldName('arguments');
    const first = args ? children(args).find((c) => c.type !== 'keyword_argument') ?? null : null;
    if (!f) return null;
    if (/^(?:os\.)?getenv$/.test(f.text)) return stringArg(first);
    if (f.type === 'attribute' && f.childForFieldName('attribute')?.text === 'get' && isEnviron(f.childForFieldName('object'))) return stringArg(first);
  }
  return null;
}

const MAX_DEPTH = 8;

export function evalPieces(n: PyNode, depth = 0): Piece[] {
  if (depth > MAX_DEPTH) return [{ k: 'dyn' }];
  switch (n.type) {
    case 'string':
      return mergePieces(stringPieces(n, depth));
    case 'concatenated_string':
      return mergePieces(children(n).flatMap((c) => evalPieces(c, depth + 1)));
    case 'parenthesized_expression': {
      const inner = children(n)[0];
      return inner ? evalPieces(inner, depth + 1) : [{ k: 'dyn' }];
    }
    case 'binary_operator': {
      const op = n.childForFieldName('operator')?.text;
      const l = n.childForFieldName('left');
      const r = n.childForFieldName('right');
      if (op === '+' && l && r) return mergePieces([...evalPieces(l, depth + 1), ...evalPieces(r, depth + 1)]);
      return [{ k: 'dyn' }];
    }
    case 'identifier': {
      const v = lookupName(n.text, n);
      return v && v !== 'opaque' ? evalPieces(v, depth + 1) : [{ k: 'dyn' }];
    }
    case 'subscript':
    case 'call': {
      const env = envNameOf(n);
      if (env) return [{ k: 'env', name: env }];
      if (n.type === 'call') {
        // "x".rstrip("/") and friends keep the receiver's text.
        const f = n.childForFieldName('function');
        if (f?.type === 'attribute' && /^(?:rstrip|lstrip|strip)$/.test(f.childForFieldName('attribute')?.text ?? '')) {
          const o = f.childForFieldName('object');
          if (o) return evalPieces(o, depth + 1);
        }
      }
      return [{ k: 'dyn' }];
    }
    default:
      return [{ k: 'dyn' }];
  }
}

/** The plain text when every piece is literal, else null. */
export function literalOf(ps: Piece[]): string | null {
  return ps.length && ps.every((p) => p.k === 'lit') ? ps.map((p) => (p as { v: string }).v).join('') : ps.length === 0 ? '' : null;
}

/** A string expression only when the whole thing is one literal (no f-string hole, no concatenation). */
export function plainString(n: PyNode | null | undefined): string | null {
  if (!n || n.type !== 'string') return null;
  const ps = stringPieces(n, 0);
  return ps.every((p) => p.k === 'lit') ? ps.map((p) => (p as { v: string }).v).join('') : null;
}


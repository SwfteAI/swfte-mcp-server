// Scope lookup: what does `name` hold at this point?

function paramNames(fn: PyNode): Set<string> {
  const out = new Set<string>();
  const params = fn.childForFieldName('parameters');
  if (!params) return out;
  walk(params, (c) => {
    if (c.type === 'identifier') {
      const p = c.parent;
      // default values and annotations are expressions, not bindings
      if (p && (p.type === 'default_parameter' || p.type === 'typed_default_parameter') && p.childForFieldName('name')?.id !== c.id) return;
      if (p && p.type === 'typed_parameter' && p.childCount > 0 && p.child(0)?.id !== c.id) return;
      out.add(c.text);
    } else if (c.type === 'default_parameter' || c.type === 'typed_default_parameter') {
      const nm = c.childForFieldName('name');
      if (nm) out.add(nm.text);
      return false;
    }
    return undefined;
  });
  return out;
}

function patternBinds(p: PyNode | null, name: string): boolean {
  if (!p) return false;
  let hit = false;
  walk(p, (c) => {
    if (c.type === 'identifier' && c.text === name) hit = true;
  });
  return hit;
}

interface Bindings {
  values: PyNode[];
  opaque: boolean;
}

// Index every name in a lexical scope once, including negative lookups. Caching one name at a
// time still walks the whole scope for each distinct call-site variable and remains quadratic.
const BINDINGS_CACHE = new WeakMap<Tree, Map<number, Map<string, Bindings>>>();

function bindingsIn(scope: PyNode, name: string): Bindings {
  let scopes = BINDINGS_CACHE.get(scope.tree);
  if (!scopes) {
    scopes = new Map();
    BINDINGS_CACHE.set(scope.tree, scopes);
  }
  let names = scopes.get(scope.id);
  if (!names) {
    names = indexBindings(scope);
    scopes.set(scope.id, names);
  }
  return names.get(name) ?? { values: [], opaque: false };
}

function indexBindings(scope: PyNode): Map<string, Bindings> {
  const names = new Map<string, Bindings>();
  const binding = (name: string): Bindings => {
    let value = names.get(name);
    if (!value) {
      value = { values: [], opaque: false };
      names.set(name, value);
    }
    return value;
  };
  const opaquePattern = (node: PyNode | null) => {
    if (!node) return;
    walk(node, (part) => { if (part.type === 'identifier') binding(part.text).opaque = true; });
  };
  const visit = (n: PyNode): boolean | void => {
    if (n.id !== scope.id && (n.type === 'function_definition' || n.type === 'class_definition')) {
      const name = n.childForFieldName('name')?.text;
      if (name) binding(name).opaque = true;
      return false;
    }
    switch (n.type) {
      case 'lambda':
        return false;
      case 'assignment': {
        const left = n.childForFieldName('left');
        const right = n.childForFieldName('right');
        if (left?.type === 'identifier') {
          const b = binding(left.text);
          if (right) b.values.push(right);
          else b.opaque = true;
        } else if (left && left.type !== 'attribute' && left.type !== 'subscript') opaquePattern(left);
        break;
      }
      case 'augmented_assignment':
        opaquePattern(n.childForFieldName('left'));
        break;
      case 'for_statement':
      case 'for_in_clause':
        opaquePattern(n.childForFieldName('left'));
        break;
      case 'as_pattern':
      case 'with_item':
        for (const child of n.children) if (child?.type === 'as_pattern_target') opaquePattern(child);
        break;
      case 'as_pattern_target':
        opaquePattern(n);
        break;
      case 'named_expression':
        {
          const name = n.childForFieldName('name')?.text;
          if (name) binding(name).opaque = true;
        }
        break;
      case 'import_statement':
      case 'import_from_statement':
        for (const name of n.text.split(/[\s,()]+/)) if (name) binding(name).opaque = true;
        break;
      case 'global_statement':
      case 'nonlocal_statement':
        opaquePattern(n);
        break;
      default:
        break;
    }
    return undefined;
  };
  walk(scope, visit);
  return names;
}

/**
 * The expression a name holds when exactly one (or several equal-text) assignments in the nearest
 * scope that binds it provide a value; 'opaque' when it is a parameter, a loop variable, reassigned
 * with different values, etc.; null when no enclosing scope binds it.
 */
export function lookupName(name: string, at: PyNode): PyNode | 'opaque' | null {
  for (let s = enclosingScope(at); s; s = enclosingScope(s.parent)) {
    if (s.type === 'function_definition' && paramNames(s).has(name)) return 'opaque';
    const b = bindingsIn(s, name);
    if (b.opaque) return 'opaque';
    if (b.values.length === 1) return b.values[0]!;
    if (b.values.length > 1) {
      const first = JSON.stringify(evalPieces(b.values[0]!, MAX_DEPTH - 2));
      return b.values.every((v) => JSON.stringify(evalPieces(v, MAX_DEPTH - 2)) === first) ? b.values[0]! : 'opaque';
    }
  }
  return null;
}

/** Whether the file imports a module whose dotted path names swfte, and whether any names a fork. */
export function swfteImports(root: PyNode): { swfte: boolean; fork: boolean } {
  let swfte = false;
  let fork = false;
  for (const st of children(root)) {
    if (st.type !== 'import_statement' && st.type !== 'import_from_statement') continue;
    const mod = st.type === 'import_from_statement' ? st.childForFieldName('module_name')?.text ?? '' : st.text.replace(/^import\s+/, '');
    const all = `${mod} ${st.text}`.toLowerCase();
    if (/swfte/.test(all)) swfte = true;
    if (/fork/.test(mod.toLowerCase())) fork = true;
  }
  return { swfte, fork };
}

// Paths that never hold call sites (decoys): tests, mocks, vendored and generated trees.

const VENDORED_DIRS = new Set(['.venv', 'venv', 'site-packages', '__pycache__', 'node_modules', 'target', 'build', 'dist', '.git', '.tox']);

export function isIgnoredPath(relPath: string): boolean {
  const segs = relPath.split('/');
  const base = segs[segs.length - 1] ?? '';
  if (segs.slice(0, -1).some((s) => VENDORED_DIRS.has(s) || s === 'tests' || s === 'test' || s === '__tests__' || s === '__mocks__' || s === 'testing')) return true;
  return /^test_.*\.py$/.test(base) || /_tests?\.py$/.test(base) || base === 'conftest.py';
}

/** Another tool's generated marker in the header (the Swfte generated client has its own marker). */
export function isForeignGenerated(text: string): boolean {
  const head = text.slice(0, 4096).split(/\r?\n/).slice(0, 40).join('\n');
  if (/Generated by @swfte\//.test(head)) return false;
  return /@generated\b/.test(head) || /Code generated\b.*\bDO NOT EDIT\b/.test(head);
}

/** A module that imports a mocking or test framework is a test even when it sits in a main tree. */
export function usesMocks(root: PyNode): boolean {
  for (const st of children(root)) {
    if (st.type !== 'import_statement' && st.type !== 'import_from_statement') continue;
    if (/^(?:from|import)\s+(?:unittest|pytest|pytest_mock|mock)\b/.test(st.text)) return true;
  }
  return false;
}


/**
 * Python parsing for the code map detectors (docs/codemap/CONTRACT.md §2.1, §7). One `web-tree-sitter`
 * parser over the vendored grammar, initialised once at import time (top-level await) because
 * `Detector.detect` is synchronous. Source text stays in this process and is never serialised.
 *
 * Everything here is structural: symbols, scope lookups, string templates. A value the code does not
 * spell out in a literal is reported as dynamic, never guessed.
 */
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { Language, Parser, type Node, type Tree } from 'web-tree-sitter';
import { mergePieces, type Piece } from './route.js';
import { initRuntime } from './runtime.js';

export type PyNode = Node;

const DEFAULT_WASM = fileURLToPath(new URL('../../grammars/tree-sitter-python.wasm', import.meta.url));
let parser: Parser | null = null;
/** Bumps every time the grammar is (re)loaded, so per-file caches never outlive their parser. */
export let grammarGeneration = 0;

/**
 * (Re)load the Python grammar. Returns false, leaving no parser, when the WASM cannot be read or
 * loaded: detectors then report nothing and the scan goes on (edge case E9).
 */
export async function initPythonParser(wasmPath: string = DEFAULT_WASM): Promise<boolean> {
  try {
    await initRuntime();
    const language = await Language.load(fs.readFileSync(wasmPath));
    const p = new Parser();
    p.setLanguage(language);
    parser = p;
    grammarGeneration++;
    return true;
  } catch {
    parser = null;
    grammarGeneration++;
    return false;
  }
}

await initPythonParser();

/** Parse and hand the tree to `fn`; the native tree is always freed. Null when no grammar is loaded. */
export function withTree<T>(text: string, fn: (root: PyNode) => T): T | null {
  if (!parser) return null;
  let tree: Tree | null = null;
  try {
    tree = parser.parse(text);
    if (!tree) return null;
    return fn(tree.rootNode);
  } catch {
    return null;
  } finally {
    if (tree) {
      // Cached Nodes reference this Tree and its source callback. Their lifetime ends here.
      NAMED_CHILDREN_CACHE.delete(tree);
      BINDINGS_CACHE.delete(tree);
      tree.delete();
    }
  }
}

